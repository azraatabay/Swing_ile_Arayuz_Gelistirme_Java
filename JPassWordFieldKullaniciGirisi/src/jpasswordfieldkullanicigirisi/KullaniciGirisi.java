    private void girisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_girisActionPerformed
        String kullanici_adi = kullanici_adi_alani.getText();
        String parola = new String(parola_alani.getPassword());
        String mesaj;
        if(kullanici_adi.equals("Azra Atabay")&& parola.equals("12345")){
            mesaj = "Hoşgeldiniz..." + kullanici_adi;
        }
        else if(!kullanici_adi.equals("Azra Atabay")&& parola.equals("12345")){
            mesaj = "Kullanıcı adı hatalı.";
        }
        else if(kullanici_adi.equals("Azra Atabay")&& !parola.equals("12345")){
            mesaj = "Parola hatalı.";
        }
        else{
            mesaj = "Kullanıcı adı veya parola hatalı.";
        }
        
        
        if (mesaj.equals("Hoşgeldiniz..." + kullanici_adi)) {
            setVisible(false);
            JOptionPane.showMessageDialog(this, mesaj);
        }
        else{
            JOptionPane.showMessageDialog(this, mesaj);
        }
        
        
        kullanici_adi_alani.setText("");
        parola_alani.setText("");
        
        
            
        
              
    }//GEN-LAST:event_girisActionPerformed

